def _question(**fields) -> dict:
    row = {
        "parent_question_id": None,
        "marks": 4,
        "negative_marks": 1,
        "option1": None,
        "option2": None,
        "option3": None,
        "option4": None,
        "correct_mcq_option": None,
        "msq_option1_answer": None,
        "msq_option2_answer": None,
        "msq_option3_answer": None,
        "msq_option4_answer": None,
        "numerical_answer": None,
        "integer_answer": None,
        "explanation": None,
        "created_at": CREATED_AT,
        "updated_at": CREATED_AT,
        "hardness_level": "easy",
        "answer": None,
    }
    row.update(fields)
    return row


def _jee_pcm(test_id: str, section_phy: str, section_chem: str, section_math: str, ids: tuple[str, str, str, str]):
    phy_mcq, phy_num, chem, math = ids
    return [
        _question(
            id=phy_mcq,
            test_id=test_id,
            section_id=section_phy,
            position=1,
            question_text="A body of mass 2 kg is acted upon by a force of 10 N. Its acceleration is:",
            question_type="mcq",
            option1="2 m/s²",
            option2="5 m/s²",
            option3="10 m/s²",
            option4="20 m/s²",
            correct_mcq_option=2,
            explanation="From F = ma, a = F/m = 10/2 = 5 m/s².",
            answer="5 m/s²",
        ),
        _question(
            id=phy_num,
            test_id=test_id,
            section_id=section_phy,
            position=2,
            question_text="The acceleration due to gravity near the Earth's surface is (take g in m/s², one decimal place):",
            question_type="numerical",
            marks=4,
            negative_marks=0,
            numerical_answer=9.8,
            explanation="Standard value used in JEE Main numericals is g = 9.8 m/s².",
            answer="9.8",
        ),
        _question(
            id=chem,
            test_id=test_id,
            section_id=section_chem,
            position=1,
            question_text="Which of the following is an alkaline earth metal?",
            question_type="mcq",
            option1="Na",
            option2="K",
            option3="Ca",
            option4="Al",
            correct_mcq_option=3,
            explanation="Calcium belongs to group 2 (alkaline earth metals). Na and K are alkali metals; Al is a p-block metal.",
            answer="Ca",
        ),
        _question(
            id=math,
            test_id=test_id,
            section_id=section_math,
            position=1,
            question_text="The number of real roots of the equation x² - 5x + 6 = 0 is:",
            question_type="integer",
            negative_marks=0,
            integer_answer=2,
            explanation="x² - 5x + 6 = (x - 2)(x - 3) = 0, so two distinct real roots.",
            answer="2",
        ),
    ]


