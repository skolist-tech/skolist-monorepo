def _adv_passage(test_id: str, section_id: str, ids: tuple[str, str, str]):
    passage, msq, integer = ids
    return [
        _question(
            id=passage,
            test_id=test_id,
            section_id=section_id,
            position=1,
            question_text=(
                "Paragraph: A particle of mass m = 1 kg moves along the x-axis under a force "
                "F = -kx, where k = 4 N/m. At t = 0 the particle is at x = 2 m with zero velocity. "
                "Answer the questions that follow."
            ),
            question_type="mcq",
            marks=0,
            negative_marks=0,
            hardness_level="medium",
            explanation="Passage stem for the two linked questions below. SHM with ω = √(k/m) = 2 rad/s.",
        ),
        _question(
            id=msq,
            test_id=test_id,
            section_id=section_id,
            parent_question_id=passage,
            position=2,
            question_text="Which of the following statements are correct?",
            question_type="msq",
            negative_marks=2,
            hardness_level="medium",
            option1="The motion is simple harmonic.",
            option2="The angular frequency is 2 rad/s.",
            option3="The total energy is 16 J.",
            option4="The amplitude is 4 m.",
            msq_option1_answer=True,
            msq_option2_answer=True,
            msq_option3_answer=False,
            msq_option4_answer=False,
            explanation=(
                "ω = √(k/m) = 2 rad/s, amplitude A = 2 m, E = (1/2)kA² = 8 J. "
                "So only (A) and (B) are correct."
            ),
            answer="A and B",
        ),
        _question(
            id=integer,
            test_id=test_id,
            section_id=section_id,
            parent_question_id=passage,
            position=3,
            question_text="The time period of oscillation in seconds is:",
            question_type="integer",
            negative_marks=0,
            hardness_level="medium",
            integer_answer=3,
            explanation="T = 2π/ω = π ≈ 3.14; the integer key used here is 3 (nearest integer).",
            answer="3",
        ),
    ]


